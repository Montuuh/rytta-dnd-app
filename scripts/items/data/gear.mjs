import { cp, gp, sp } from './units.mjs'

const g = (key, en, es, category, icon, weightLb, costCp, descEn, descEs, extra = {}) => ({
  key,
  name: { en, es },
  description: { en: descEn, es: descEs },
  category,
  icon,
  weightLb,
  costCp,
  ...extra,
})
const ammo = (key, en, es, icon, quantity, packWeightLb, packCostCp, storage) => ({
  key,
  name: { en, es },
  description: {
    en: `Ammunition for weapons with the Ammunition property. Each attack expends one piece; after a fight you can spend 1 minute to recover half of what you used. Sold in lots of ${quantity}; usually stored in a ${storage[0]}.`,
    es: `Munición para las armas con la propiedad de munición. Cada ataque gasta una unidad; tras un combate puedes dedicar 1 minuto a recuperar la mitad de la que hayas usado. Se vende en lotes de ${quantity}; suele guardarse en ${storage[1]}.`,
  },
  category: 'ammo',
  icon,
  weightLb: packWeightLb / quantity,
  // The SRD prices ammunition per lot; the unit price is rounded up to a whole copper piece.
  costCp: Math.ceil(packCostCp / quantity),
  pack: { quantity, weightLb: packWeightLb, costCp: packCostCp },
})
const focus = (key, en, es, icon, weightLb, cost, kind, extra = {}) => ({
  key,
  name: { en, es },
  description: kind,
  category: 'gear',
  icon,
  weightLb,
  costCp: gp(cost),
  ...extra,
})

const abilities = {
  str: ['Strength', 'Fuerza'],
  dex: ['Dexterity', 'Destreza'],
  int: ['Intelligence', 'Inteligencia'],
  wis: ['Wisdom', 'Sabiduría'],
  cha: ['Charisma', 'Carisma'],
}
const tool = (key, en, es, icon, ability, weightLb, costCp, utilizeEn, utilizeEs) => ({
  key,
  name: { en, es },
  description: {
    en: `Ability: ${abilities[ability][0]}. Utilize: ${utilizeEn}.`,
    es: `Característica: ${abilities[ability][1]}. Utilizar: ${utilizeEs}.`,
  },
  category: 'tool',
  icon,
  weightLb,
  costCp,
})
const game = (key, en, es, costCp) =>
  tool(
    key,
    en,
    es,
    'gift',
    'wis',
    0,
    costCp,
    'Discern whether someone is cheating (DC 10), or win the game (DC 20)',
    'distinguir si alguien hace trampas (CD 10) o ganar la partida (CD 20)',
  )
const instrument = (key, en, es, cost, weightLb) =>
  tool(
    key,
    en,
    es,
    'feather',
    'cha',
    weightLb,
    gp(cost),
    'Play a known tune (DC 10), or improvise a song (DC 15)',
    'tocar una melodía conocida (CD 10) o improvisar una canción (CD 15)',
  )


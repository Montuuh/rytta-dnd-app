/** Editor state of a homebrew creature (ADR 028). Derived numbers are computed, not typed. */
export type UsageChoice = 'none' | 'r6' | 'r5' | 'r4' | 'd1' | 'd2' | 'd3'
export type DraftEntry = {
  uid: string
  key: string
  name: string
  usage: UsageChoice
  text: string
  spells?: StatEntry['spells']
}
export type CreatureDraft = {
  name: string
  side: 'enemy' | 'ally'
  size: CreatureSize
  type: CreatureType
  tags: string
  alignment: string
  meta: string
  metaAuto: boolean
  cr: string
  ac: number
  acNote: string
  hitDice: number
  hitDie: number
  initiativeExtra: number
  speed: string
  abilities: Record<AbilityKey, number>
  saves: AbilityKey[]
  details: Record<DetailKey, string>
  legendary: number
  sections: Record<SectionKind, DraftEntry[]>
  notes: string
  srdId: string | null
}

const FEMININE_ES: CreatureType[] = ['aberration', 'beast', 'monstrosity', 'plant']
let uidCounter = 0
export const draftUid = () => `e${++uidCounter}-${Date.now().toString(36)}`

export function metaLine(
  t: TFunction,
  language: BestiaryLanguage,
  draft: Pick<CreatureDraft, 'size' | 'type' | 'tags' | 'alignment'>,
) {
  const type = t(`bestiary.type.${draft.type}`)
  const tags = draft.tags.trim() ? ` (${draft.tags.trim()})` : ''
  const alignment = draft.alignment.trim()
  const head =
    language === 'es'
      ? `${type} ${t(
          FEMININE_ES.includes(draft.type)
            ? `bestiary.sizeF.${draft.size}`
            : `bestiary.size.${draft.size}`,
        )}${tags}`
      : `${t(`bestiary.size.${draft.size}`)} ${type}${tags}`
  return alignment ? `${head}, ${alignment}` : head
}

export const usageOf = (choice: UsageChoice): StatEntry['usage'] =>
  choice === 'none'
    ? undefined
    : choice.startsWith('r')
      ? { recharge: Number(choice[1]) }
      : { perDay: Number(choice[1]) }
const choiceOf = (usage: StatEntry['usage']): UsageChoice => {
  if (usage?.recharge && [4, 5, 6].includes(usage.recharge))
    return `r${usage.recharge}` as UsageChoice
  if (usage?.perDay && [1, 2, 3].includes(usage.perDay)) return `d${usage.perDay}` as UsageChoice
  return 'none'
}

const emptySections = (): Record<SectionKind, DraftEntry[]> => ({
  traits: [],
  actions: [],
  bonusActions: [],
  reactions: [],
  legendaryActions: [],
})
const emptyDetails = () =>
  Object.fromEntries(detailKeys.map((k) => [k, ''])) as Record<DetailKey, string>

export function blankDraft(t: TFunction, language: BestiaryLanguage, name = ''): CreatureDraft {
  const draft: CreatureDraft = {
    name,
    side: 'enemy',
    size: 'medium',
    type: 'humanoid',
    tags: '',
    alignment: t('bestiary.editor.defaultAlignment'),
    meta: '',
    metaAuto: true,
    cr: '1',
    ac: 13,
    acNote: '',
    hitDice: 4,
    hitDie: 8,
    initiativeExtra: 0,
    speed: t('bestiary.arch.speed'),
    abilities: { str: 10, dex: 10, con: 10, int: 10, wis: 10, cha: 10 },
    saves: [],
    details: emptyDetails(),
    legendary: 0,
    sections: emptySections(),
    notes: '',
    srdId: null,
  }
  draft.meta = metaLine(t, language, draft)
  return draft
}

/** Reads a stat block (SRD, archetype or pasted) into the editor. */
export function draftFromBlock(
  t: TFunction,
  language: BestiaryLanguage,
  block: StatBlock,
  hints: {
    size?: CreatureSize | null
    type?: CreatureType | null
    cr?: string | null
    legendary?: number
    side?: 'enemy' | 'ally'
    srdId?: string | null
    notes?: string
    name?: string
    /** The block's type line was generated by Rytta (archetypes): keep it in sync. */
    metaAuto?: boolean
  } = {},
): CreatureDraft {
  const draft = blankDraft(t, language, hints.name ?? block.name)
  draft.size = hints.size ?? draft.size
  draft.type = hints.type ?? draft.type
  draft.side = hints.side ?? 'enemy'
  draft.srdId = hints.srdId ?? null
  draft.notes = hints.notes ?? ''
  if (hints.cr && (challengeRatings as readonly string[]).includes(hints.cr)) draft.cr = hints.cr
  const acMatch = block.ac.match(/^(\d+)\s*(.*)$/)
  if (acMatch) {
    draft.ac = Number(acMatch[1])
    draft.acNote = acMatch[2]!.replace(/^\(|\)$/g, '').trim()
  }
  for (const key of abilityKeys)
    if (block.abilities[key]) draft.abilities[key] = block.abilities[key]!.score
  draft.saves = abilityKeys.filter(
    (k) => block.abilities[k] && block.abilities[k]!.save > block.abilities[k]!.mod,
  )
  const dice = block.hpFormula ? parseDice(block.hpFormula) : null
  if (dice) {
    draft.hitDice = dice.count
    draft.hitDie = dice.faces
  } else {
    draft.hitDie = hitDieBySize[draft.size]
    const hp = Number(block.hp.match(/\d+/)?.[0] ?? 0)
    const per = (draft.hitDie + 1) / 2 + abilityModifier(draft.abilities.con)
    draft.hitDice = Math.max(1, Math.round(hp / Math.max(1, per)))
  }
  const init = Number(block.initiative.replace(/[−–]/g, '-').match(/[+-]?\d+/)?.[0] ?? NaN)
  if (Number.isFinite(init)) draft.initiativeExtra = init - abilityModifier(draft.abilities.dex)
  draft.speed = block.speed
  for (const key of detailKeys) draft.details[key] = (block.details[key] ?? '').replace(/\*+/g, '')
  // Passive Perception is recomputed on save.
  draft.details.senses = draft.details.senses
    .replace(/[;,]?\s*(?:passive perception|percepción pasiva)\s*\d+/i, '')
    .trim()
  draft.legendary = hints.legendary ?? 0
  for (const section of block.sections) {
    draft.sections[section.kind] = section.entries.map((e) => ({
      uid: draftUid(),
      key: e.key,
      name: e.name,
      usage: choiceOf(e.usage),
      text: e.text.join('\n\n'),
      ...(e.spells ? { spells: e.spells } : {}),
    }))
    if (section.kind === 'legendaryActions' && !draft.legendary)
      draft.legendary = Number(section.intro?.match(/\d+/)?.[0] ?? 3)
  }
  // Tags and alignment come from the type line ("Large Fiend (Devil), Lawful Evil").
  const meta = block.meta.trim()
  const comma = meta.lastIndexOf(',')
  if (comma > 0)
    draft.alignment = meta
      .slice(comma + 1)
      .trim()
      .slice(0, 40)
  const tags = meta.slice(0, comma > 0 ? comma : undefined).match(/\(([^)]+)\)/)
  if (tags) draft.tags = tags[1]!.trim().slice(0, 40)
  draft.metaAuto = hints.metaAuto === true || meta.length === 0
  draft.meta = draft.metaAuto ? metaLine(t, language, draft) : meta
  return draft
}

export type DraftNumbers = {
  pb: number
  xp: number
  hp: number
  formula: string
  dice: string
  initiative: number
  passive: number
  mods: Record<AbilityKey, number>
  saves: Record<AbilityKey, number>
}

export function draftNumbers(draft: CreatureDraft): DraftNumbers {
  const pb = proficiencyForCr(draft.cr)
  const mods = Object.fromEntries(
    abilityKeys.map((k) => [k, abilityModifier(draft.abilities[k])]),
  ) as Record<AbilityKey, number>
  const saves = Object.fromEntries(
    abilityKeys.map((k) => [k, mods[k] + (draft.saves.includes(k) ? pb : 0)]),
  ) as Record<AbilityKey, number>
  const dice = { count: draft.hitDice, faces: draft.hitDie, bonus: draft.hitDice * mods.con }
  const perception = draft.details.skills
    .replace(/[−–]/g, '-')
    .match(/(?:perception|percepción)\s*([+-]\d+)/i)
  return {
    pb,
    xp: xpForCr(draft.cr),
    hp: averageDice(dice),
    formula: diceKey(dice),
    dice: diceText(dice),
    initiative: mods.dex + draft.initiativeExtra,
    passive: 10 + (perception ? Number(perception[1]) : mods.wis),
    mods,
    saves,
  }
}

const slug = (text: string) =>
  text
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/\(.*?\)/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60) || 'entry'

/** The stat block and the template fields the server stores. */
export function draftToTemplate(
  t: TFunction,
  draft: CreatureDraft,
): { input: TemplateInput; block: StatBlock } {
  const n = draftNumbers(draft)
  const used = new Set<string>()
  const sections = sectionKinds
    .map((kind) => ({
      kind,
      ...(kind === 'legendaryActions' && draft.sections[kind].length
        ? {
            intro: t('bestiary.legendaryIntro', {
              count: draft.legendary || 1,
              name: draft.name.trim(),
            }),
          }
        : {}),
      entries: draft.sections[kind]
        .filter((e) => e.name.trim())
        .slice(0, 40)
        .map((e) => {
          let key = e.key && !used.has(e.key) ? e.key : slug(e.name)
          for (let i = 2; used.has(key); i++) key = `${slug(e.name)}-${i}`
          used.add(key)
          const usage = usageOf(e.usage)
          return {
            key,
            name: e.name.trim().slice(0, 120),
            text: e.text
              .split(/\n\s*\n/)
              .map((p) => p.replace(/\s*\n\s*/g, ' ').trim())
              .filter(Boolean)
              .slice(0, 12),
            ...(usage ? { usage } : {}),
            ...(e.spells ? { spells: e.spells } : {}),
          }
        }),
    }))
    .filter((s) => s.entries.length > 0)
  const senses = [draft.details.senses.trim(), t('bestiary.passive', { value: n.passive })]
    .filter(Boolean)
    .join('; ')
  const details = Object.fromEntries(
    detailKeys
      .map((k) => [k, k === 'senses' ? senses : draft.details[k].trim()] as const)
      .filter(([, v]) => v),
  ) as StatBlock['details']
  const block: StatBlock = {
    name: draft.name.trim().slice(0, 120),
    meta: draft.meta.trim().slice(0, 200),
    ac: (draft.acNote.trim() ? `${draft.ac} (${draft.acNote.trim()})` : String(draft.ac)).slice(
      0,
      80,
    ),
    initiative: `${signed(n.initiative)} (${10 + n.initiative})`,
    hp: `${n.hp} (${n.dice})`,
    hpFormula: n.formula,
    speed: draft.speed.trim().slice(0, 200),
    abilities: Object.fromEntries(
      abilityKeys.map((k) => [k, { score: draft.abilities[k], mod: n.mods[k], save: n.saves[k] }]),
    ) as StatBlock['abilities'],
    details,
    cr: t('bestiary.crLine', { cr: draft.cr, xp: n.xp.toLocaleString(), pb: n.pb }),
    sections,
  }
  return {
    block,
    input: {
      name: draft.name.trim().slice(0, 80),
      side: draft.side,
      max_hp: Math.min(99999, n.hp),
      armor_class: Math.max(0, Math.min(99, draft.ac)),
      initiative_bonus: Math.max(-20, Math.min(30, n.initiative)),
      legendary_max: draft.sections.legendaryActions.length ? Math.min(9, draft.legendary || 1) : 0,
      notes: draft.notes.slice(0, 2000),
      stat_block: block,
      srd_id: draft.srdId,
      hp_formula: n.formula,
      challenge: draft.cr,
      creature_type: draft.type,
    },
  }
}

export const isCreatureSize = (v: string): v is CreatureSize =>
  (creatureSizes as readonly string[]).includes(v)
export const isCreatureType = (v: string): v is CreatureType =>
  (creatureTypes as readonly string[]).includes(v)
